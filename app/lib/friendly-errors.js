// Importzo — Friendly error translation
//
// Turns raw Shopify / HTTP errors into human-readable strings so
// merchants never see things like `HTTP 422` or `{"errors":{"handle"
// :["has already been taken"]}}`. One place to grow the lookup table.
// ═══════════════════════════════════════════════════════════════════

const PATTERNS = [
  [/handle.*already been taken/i, "An item with this handle already exists in the destination store. Use Skip or Overwrite mode to control this."],
  [/title.*can't be blank/i, "Missing title — Shopify requires every product to have a title."],
  [/price.*(must be|can't)/i, "Invalid price on one or more variants."],
  [/exceeds the limit|too many/i, "This store has reached a Shopify resource limit (e.g. max products, variants, or images). Check your plan's limits."],
  [/body.*too (large|long)/i, "The HTML description is too long. Shopify limits product body HTML to ~512KB."],
  [/variant.*limit/i, "Shopify allows a maximum of 100 variants per product. Products with more variants were skipped."],
  [/option.*can't have more than/i, "Shopify allows at most 3 options per product. Extra options were ignored."],
  [/HTTP 401/i, "Authentication failed. The access token may be invalid or expired — reconnect your source store."],
  [/HTTP 403/i, "Permission denied. The access token is missing one of the required read scopes on the source store."],
  [/HTTP 404/i, "The requested resource wasn't found on the source store."],
  [/HTTP 422/i, "The destination store rejected this item as invalid. Common causes: missing required fields, invalid pricing, or a duplicate handle."],
  [/HTTP 429|throttl/i, "Shopify rate-limited the request. This is temporary — the transfer continued for other items. Retry just the failed ones."],
  [/HTTP 5\d\d/i, "Shopify had a temporary server error. This is usually transient — retry in a moment."],
  [/ENOTFOUND|ECONN|network|ETIMEDOUT/i, "Couldn't reach the store. Check the URL and your internet connection."],
  [/image.*(invalid|failed|unsupported)/i, "One or more product images couldn't be uploaded. The item was created without them."],
  [/Fetch failed/i, "Could not download this file from the source store. The URL may be private or expired."],
  [/No content available/i, "This asset has no downloadable content — it may be generated by the theme engine."],
];

export function friendlyError(raw) {
  if (!raw) return "Unknown error";
  const msg = typeof raw === "string" ? raw : (raw.message || JSON.stringify(raw));
  for (const [pattern, friendly] of PATTERNS) {
    if (pattern.test(msg)) return friendly;
  }
  // Strip verbose JSON-encoded Shopify error objects
  const trimmed = msg.replace(/[{}"[\]]/g, " ").replace(/\s+/g, " ").trim();
  return trimmed.length > 160 ? trimmed.slice(0, 157) + "..." : trimmed;
}

// Summarize a batch of failed items into a few human-readable groups
export function summarizeFailures(errors) {
  if (!errors || errors.length === 0) return [];
  const groups = new Map();
  for (const e of errors) {
    const f = friendlyError(e.error || e.message || e);
    groups.set(f, (groups.get(f) || 0) + 1);
  }
  return [...groups.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([message, count]) => ({ message, count }));
}
